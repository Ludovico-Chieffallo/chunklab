"""`chunklab bootstrap` writes a draft the user then spends an afternoon editing.

Running it again - to try another `-n`, or by pressing up-arrow in the shell -
silently replaced that edited file with a fresh draft. The edits were gone, with no
warning and nothing to undo.
"""

from pathlib import Path

EXAMPLES = Path(__file__).parent.parent / "examples" / "corpus"
EDITED = "# my carefully edited questions\nquestions: []\n"


def test_an_existing_draft_is_not_overwritten(tmp_path, cli):
    out = tmp_path / "questions.draft.yaml"
    out.write_text(EDITED, encoding="utf-8")

    result = cli("bootstrap", "--docs", EXAMPLES, "--out", out, "-n", "3")

    assert result.exit_code == 2
    assert "already exists" in result.output and "--force" in result.output
    assert out.read_text(encoding="utf-8") == EDITED


def test_force_overwrites_on_purpose(tmp_path, cli):
    out = tmp_path / "questions.draft.yaml"
    out.write_text(EDITED, encoding="utf-8")

    result = cli("bootstrap", "--docs", EXAMPLES, "--out", out, "-n", "3", "--force")

    assert result.exit_code == 0, result.output
    assert out.read_text(encoding="utf-8").startswith("# Generated by `chunklab bootstrap`")


def test_a_new_draft_is_written_as_before(tmp_path, cli):
    out = tmp_path / "questions.draft.yaml"

    result = cli("bootstrap", "--docs", EXAMPLES, "--out", out, "-n", "3")

    assert result.exit_code == 0, result.output
    assert out.is_file()


def test_the_refusal_comes_before_the_documents_are_read(tmp_path, cli):
    """Refusing should cost nothing: the existing file is checked first."""
    out = tmp_path / "questions.draft.yaml"
    out.write_text(EDITED, encoding="utf-8")

    result = cli("bootstrap", "--docs", tmp_path / "missing", "--out", out)

    assert result.exit_code == 2
    assert "already exists" in result.output
